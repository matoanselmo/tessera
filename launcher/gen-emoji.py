#!/usr/bin/env python3
"""Generates launcher/Emoji.js, the launcher's emoji list, from Unicode names.

Run from the repo root:  python3 launcher/gen-emoji.py

Uses Python's unicodedata (no download), so the list follows the Unicode
version Python ships. Single code points only: skin tones, flags and ZWJ
sequences need data unicodedata does not have.
"""
import json
import unicodedata
from pathlib import Path

# Blocks that are (almost) all emoji.
RANGES = [
    (0x1F300, 0x1F5FF),  # Miscellaneous Symbols and Pictographs
    (0x1F600, 0x1F64F),  # Emoticons
    (0x1F680, 0x1F6FF),  # Transport and Map Symbols
    (0x1F7E0, 0x1F7EB),  # Coloured circles and squares
    (0x1F900, 0x1F9FF),  # Supplemental Symbols and Pictographs
    (0x1FA70, 0x1FAFF),  # Symbols and Pictographs Extended-A
]

# Skin tone modifiers: meaningless on their own.
SKIP = set(range(0x1F3FB, 0x1F400))

# From the older symbol blocks, only the characters that are emoji; most of
# their neighbours are plain text symbols.
CLASSIC = (
    "☀☁☂☃☄★☎☑☔☕☘☝☠☢☣☦☪☮☯☸☹☺♀♂♈♉♊♋♌♍♎♏♐♑♒♓♟♠♣♥♦♨♻♾♿"
    "⚒⚓⚔⚕⚖⚗⚙⚛⚜⚠⚡⚧⚪⚫⚰⚱⚽⚾⛄⛅⛈⛎⛏⛑⛓⛔⛩⛪⛰⛱⛲⛳⛴⛵⛷⛸⛹⛺⛽"
    "✂✅✈✉✊✋✌✍✏✒✔✖✝✡✨✳✴❄❇❌❎❓❔❕❗❣❤➕➖➗➡➰➿⌚⌛⏰⏳⬛⬜⭐⭕"
)


def entries():
    chars = [chr(c) for lo, hi in RANGES for c in range(lo, hi + 1) if c not in SKIP]
    chars += list(CLASSIC)
    for ch in chars:
        name = unicodedata.name(ch, "")
        if name:
            yield [ch, name.lower()]


def main():
    data = list(entries())
    out = Path(__file__).with_name("Emoji.js")
    out.write_text(
        ".pragma library\n\n"
        "// Generated by launcher/gen-emoji.py from Unicode "
        f"{unicodedata.unidata_version} names; do not edit by hand.\n"
        "// Each entry is [emoji, lower-case name].\n"
        f"const list = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    print(f"wrote {len(data)} emoji to {out}")


if __name__ == "__main__":
    main()
